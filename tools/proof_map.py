def defs(rel):
    return {n.name: n.lineno for n in ast.walk(ast.parse((R / rel).read_text())) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}


def render():
    idx = {k: defs(v) for k, v in FILES.items()}
    out, missing = ["## Proof by AC", "Generated by `python3 tools/proof_map.py` from test names (line = the test's `def` line)."], []
    for label, refs in ROWS:
        cells = []
        for f, name in refs:
            if name not in idx[f]:
                missing.append(f"{FILES[f]}::{name}")
                continue
            cells.append(f"`{FILES[f]}:{idx[f][name]}` {name}")
        out.append(f"- **{label}:** " + "; ".join(cells))
    return "\n".join(out) + "\n", missing


if __name__ == "__main__":
    text, missing = render()
    if missing:
        sys.exit("proof_map: missing tests: " + ", ".join(missing))
    sys.stdout.write(text)
